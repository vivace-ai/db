import json

doc = ("[국내 출장 규정] 제7조 해외 출장은 해외 출장 규정을 따른다. "
       "제9조 법인카드 사용은 법인카드 규정을 함께 본다. "
       "제10조 이 규정은 재무팀이 관리한다.")

prompt = f"""다음 규정에서 사실을 뽑아 JSON 목록으로 답하라.
관계는 담당(규정→부서), 관련(규정→규정) 두 가지만 쓴다.
문서: {doc}"""

# 위 prompt를 LLM에 보내면 돌아올 법한 답의 예 (실제로는 매번 조금씩 다르다)
reply = """[
 {"출발": "국내 출장 규정", "관계": "관리",
  "도착": "재무팀", "근거": "제10조"},
 {"출발": "국내 출장 규정", "관계": "관련",
  "도착": "해외 출장 규정", "근거": "제7조"},
 {"출발": "국내 출장 규정", "관계": "관련",
  "도착": "법인카드 규정", "근거": "제9조"},
 {"출발": "재무팀", "관계": "담당",
  "도착": "법인카드 규정", "근거": "제9조"},
 {"출발": "국내 출장 규정", "관계": "관련",
  "도착": "경비 정산 지침", "근거": "제12조"},
 {"출발": "국내 출장 규정", "관계": "승인",
  "도착": "준호", "근거": "제10조"}]"""

kinds = {"국내 출장 규정": "규정", "해외 출장 규정": "규정", "법인카드 규정": "규정",
         "경비 정산 지침": "규정",
         "재무팀": "부서", "준호": "직원"}
relations = {"담당": ("규정", "부서"), "관련": ("규정", "규정")}   # 17장 약속 + 관련
synonyms = {"관리": "담당", "책임": "담당"}

graph = []
for f in json.loads(reply):
    rel = synonyms.get(f["관계"], f["관계"])
    fact = f'{f["출발"]} -{rel}→ {f["도착"]}'
    if rel not in relations:
        print(f"✕ {fact}: 약속에 없는 관계")
    elif (kinds.get(f["출발"]), kinds.get(f["도착"])) != relations[rel]:
        print(f"✕ {fact}: 방향이나 종류가 약속과 다르다")
    elif f["근거"] not in doc:
        print(f"✕ {fact}: 근거({f['근거']})를 문서에서 찾을 수 없다")
    else:
        graph.append((f["출발"], rel, f["도착"], f["근거"]))
        print(f"✓ {fact} (근거: {f['근거']})")
print(f"그래프에 넣은 사실 {len(graph)}개")
